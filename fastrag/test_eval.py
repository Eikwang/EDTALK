def query(question: str) -> dict:
    resp = requests.post(f"{BASE_URL}/query", json={"question": question}, timeout=120)
    return resp.json()

def evaluate_answer(question, answer, expected_keywords, category, style):
    """评估单个回答的质量"""
    answer_lower = answer.lower()
    issues = []
    score = 10.0  # 满分10分

    # 1. 准确性: 是否包含关键信息 (4分)
    hits = [kw for kw in expected_keywords if kw.lower() in answer_lower]
    accuracy = len(hits) / max(len(expected_keywords), 1)
    if accuracy < 0.5:
        issues.append(f"关键信息缺失 (命中:{hits}/{expected_keywords})")
        score -= 3
    elif accuracy < 1.0:
        score -= 1

    # 2. AI套话检测: 不应出现这些 (2分)
    ai_cliches = ["根据资料", "参考资料", "根据提供", "作为AI", "作为人工智能",
                   "根据文档", "基于以上", "综上所述", "资料显示", "根据参考"]
    found_cliches = [c for c in ai_cliches if c in answer]
    if found_cliches:
        issues.append(f"AI套话: {found_cliches}")
        score -= 2

    # 3. 自然度: 应有语气词 (1分)
    tones = ["哦", "呢", "的", "呐", "呗", "~", "！"]
    has_tone = any(t in answer for t in tones)
    if not has_tone:
        issues.append("缺少语气词")
        score -= 0.5

    # 4. 长度: 应在 5-50 字之间 (1分)
    char_count = len(answer)
    if char_count < 3:
        issues.append(f"回答过短 ({char_count}字)")
        score -= 1
    elif char_count > 50:
        issues.append(f"回答过长 ({char_count}字, 上限50)")
        score -= 0.5

    # 5. 角色感: 主播语气 (1分)
    anchor_signs = ["亲", "宝子", "宝宝们", "家人们", "咱们", "这", "那"]
    has_anchor = any(s in answer for s in anchor_signs)
    if not has_anchor and not has_tone:
        score -= 0.5

    # 6. 否定类问题应正确纠正误解 (1分)
    if style == "否定":
        # 否定类问题应该给出纠正性回答，不应顺着错误方向回答
        neg_wrong = ["是的", "可以的", "没问题", "完全可以"]
        has_wrong = any(w in answer for w in neg_wrong)
        if has_wrong and accuracy < 0.5:
            issues.append("否定问题未正确纠正")
            score -= 1

    # 7. 拒绝类问题应得体 (1分)
    if category == "边界":
        polite = ["不卖", "没有", "耗材", "清洁用品", "不做"]
        has_polite = any(p in answer_lower for p in polite)
        if not has_polite:
            issues.append("边界问题回答不当")
            score -= 1

    return max(0, score), issues, hits


